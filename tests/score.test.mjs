import assert from 'node:assert/strict';
import {scoreLocation,referenceFromRows,groupSectors,pickCandidates} from '../js/score-core.js';
import {rawLocation} from '../js/synthetic-data.js';
const cal={Rlo:20,Rhi:500,Llo:50,Lhi:6000};
const raw={status:'scored',wallM:20,footM:10,footObserved:true,resRaw:200,livingRaw:1400};
const ref=referenceFromRows(Array.from({length:10},(_,i)=>({wallM:5+i*5,footM:2+i*2,footObserved:true})));
const baseline=scoreLocation(raw,{method:'absolute',reference:ref,calibration:cal});
const mix=scoreLocation(raw,{method:'mixed',reference:ref,calibration:cal});
assert.equal(Number(baseline.absScore.toFixed(6)),Number((35*.4+25*.4+25*((500-200)/480)+15*((6000-1400)/5950)).toFixed(6)));
assert.equal(mix.score,mix.mixedScore);
assert.equal(mix.absScore,baseline.score);
assert.notEqual(mix.score,baseline.score);
assert.equal(scoreLocation({...raw,status:'blocked'},{method:'mixed',reference:ref,calibration:cal}),null);
const missing=scoreLocation({...raw,footObserved:false},{method:'mixed',reference:ref,calibration:cal});
assert.equal(missing.relativeFactors[1],baseline.factors[1]);
assert.equal(missing.warnings.length,1);
const rows=[...Array(4)].map((_,i)=>({i,j:0,x:i*10,y:0,wallM:8,p:{score:70}}));
const ss=groupSectors(rows);
assert.equal(ss.reduce((s,x)=>s+x.cells.length,0),4);
assert.equal(ss.length,1);
assert.equal(pickCandidates(rows,2,20).length,2);
assert.equal(rawLocation(112,120).status,'blocked');
console.log('SmokeSpot demo public scoring tests PASS');
const changedRef={wall:[0,25],foot:[0,25]};
const origAgain=scoreLocation(raw,{method:'absolute',reference:changedRef,calibration:cal});
const mixedAgain=scoreLocation(raw,{method:'mixed',reference:changedRef,calibration:cal});
assert.equal(origAgain.score,baseline.score,'absolute P invariant to search-area reference');
assert.notEqual(mixedAgain.score,mix.score,'mixed P can depend on the selected area');
const many=Array.from({length:110},(_,i)=>({i,j:0,x:i*10,y:0,p:{score:72}}));
const grouped=groupSectors(many);
assert.equal(grouped.flatMap(x=>x.cells).length,110,'all scored cells must be in a sector');
assert(grouped.every(x=>x.cells.length<=65),'sector cap should be respected');
